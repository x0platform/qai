#!/usr/bin/env node
/**
 * Generate test PDF files of specific sizes for upload validation tests.
 * 
 * Creates:
 *   - test-data/pdfs/valid-2mb.pdf  (exactly 2 MB)
 *   - test-data/pdfs/invalid-2mb-plus.pdf (> 2 MB, e.g. 2.1 MB)
 */

import fs from 'fs';
import path from 'path';

const PDF_DIR = path.resolve(process.cwd(), 'test-data/pdfs');

// Minimal valid PDF-1.4 structure (single blank page)
const MINIMAL_PDF = `%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] >>
endobj
xref
0 4
0000000000 65535 f 
0000000009 00000 n 
0000000058 00000 n 
0000000115 00000 n 
trailer
<< /Size 4 /Root 1 0 R >>
startxref
178
%%EOF
`;

function padToSize(content: string, targetSizeBytes: number): Buffer {
  const contentBytes = Buffer.from(content, 'utf-8');
  if (contentBytes.length >= targetSizeBytes) {
    return contentBytes.slice(0, targetSizeBytes);
  }
  const paddingNeeded = targetSizeBytes - contentBytes.length;
  // Pad with PDF comment lines (each line starts with % and ends with newline)
  const commentLine = '% Generated by QAI test data generator - padding byte ' + 'x'.repeat(80) + '\n';
  const commentBuffer = Buffer.from(commentLine, 'utf-8');
  const paddingChunks = Math.ceil(paddingNeeded / commentBuffer.length);
  const padding = Buffer.alloc(paddingNeeded);
  let offset = 0;
  for (let i = 0; i < paddingChunks && offset < paddingNeeded; i++) {
    const chunk = commentBuffer.slice(0, Math.min(commentBuffer.length, paddingNeeded - offset));
    chunk.copy(padding, offset);
    offset += chunk.length;
  }
  return Buffer.concat([contentBytes, padding]);
}

const TWO_MB = 2 * 1024 * 1024; // 2,097,152 bytes
const TWO_POINT_ONE_MB = 2.1 * 1024 * 1024; // 2,202,009.6 -> 2,202,010 bytes

function generate(): void {
  fs.mkdirSync(PDF_DIR, { recursive: true });

  // Valid 2MB PDF
  const validPdf = padToSize(MINIMAL_PDF, TWO_MB);
  const validPath = path.join(PDF_DIR, 'valid-2mb.pdf');
  fs.writeFileSync(validPath, validPdf);
  console.log(`Generated ${validPath} (${validPdf.length} bytes, ${(validPdf.length / (1024 * 1024)).toFixed(2)} MB)`);

  // Invalid >2MB PDF (2.1 MB)
  const invalidPdf = padToSize(MINIMAL_PDF, TWO_POINT_ONE_MB);
  const invalidPath = path.join(PDF_DIR, 'invalid-2mb-plus.pdf');
  fs.writeFileSync(invalidPath, invalidPdf);
  console.log(`Generated ${invalidPath} (${invalidPdf.length} bytes, ${(invalidPdf.length / (1024 * 1024)).toFixed(2)} MB)`);
}

generate();
